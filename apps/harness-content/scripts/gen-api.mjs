// Regenerates src/api/schema.d.ts from harness-content-api's OpenAPI document.
// Needs no running server: the schema comes straight from the FastAPI app via uv.
import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"
import { registerHooks } from "node:module"

// openapi-typescript needs TypeScript 5's JS compiler API, which TypeScript 7 does not ship;
// route its `typescript` import to the `typescript5` alias.
const ts5 = import.meta.resolve("typescript5")
registerHooks({
  resolve: (specifier, context, next) =>
    specifier === "typescript" ? { url: ts5, shortCircuit: true } : next(specifier, context),
})
const { default: openapiTS, astToString } = await import("openapi-typescript")

const json = execFileSync(
  "uv",
  [
    "run",
    "python",
    "-c",
    "import json; from harness_content_api.main import app; print(json.dumps(app.openapi()))",
  ],
  { encoding: "utf8" },
)
// Fields with server defaults stay optional in request bodies.
const ast = await openapiTS(JSON.parse(json), { defaultNonNullable: false })
const header = "// Generated by `pnpm gen:api` from harness-content-api. Do not edit.\n"
writeFileSync(new URL("../src/api/schema.d.ts", import.meta.url), header + astToString(ast))
console.log("wrote src/api/schema.d.ts")
